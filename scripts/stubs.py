"""Writes metatraderx/__init__.pyi and metatraderx/offline.pyi so editors show the signatures and docstrings of the
module-level functions (`mt5.copy_rates_from`), which are created at import time and are invisible to static analysis.

Run after changing the MetaTrader class:  python scripts/stubs.py
"""

from __future__ import annotations

import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import metatraderx as mtx  # noqa: E402
from metatraderx.backends.base import API  # noqa: E402

PKG = ROOT / "metatraderx"
BANNER = "# Generated by scripts/stubs.py from the MetaTrader class; do not edit by hand.\n"

TYPES = (
    "AccountInfo", "BookInfo", "OrderCheckResult", "OrderSendResult", "SymbolInfo", "TerminalInfo", "Tick",
    "TradeDeal", "TradeOrder", "TradePosition", "TradeRequest",
)  # fmt: skip
ERRORS = ("AuthError", "BackendError", "MTXError", "NotConnected", "RemoteError", "SetupError", "SetupWarning", "TerminalNotFound")


def _doc(text: str | None, indent: str) -> str:
    if not text:
        return ""
    body = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = body.splitlines()
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""\n'
    rest = "\n".join((indent + ln) if ln else "" for ln in lines[1:])
    return f'{indent}"""{lines[0]}\n{rest}\n{indent}"""\n'


def _default(v: object) -> str:
    return repr(v) if v is None or isinstance(v, (bool, int, float, str)) else "..."


def _func(name: str, fn: object) -> str:
    sig = inspect.signature(fn)  # type: ignore[arg-type]
    parts: list[str] = []
    star = False
    for p in sig.parameters.values():
        if p.name == "self":
            continue
        ann = "" if p.annotation is inspect.Parameter.empty else f": {p.annotation}"
        if p.kind is p.VAR_POSITIONAL:
            parts.append(f"*{p.name}{ann}")
            star = True
            continue
        if p.kind is p.VAR_KEYWORD:
            parts.append(f"**{p.name}{ann}")
            continue
        if p.kind is p.KEYWORD_ONLY and not star:
            parts.append("*")
            star = True
        default = "" if p.default is inspect.Parameter.empty else f" = {_default(p.default)}" if ann else f"={_default(p.default)}"
        parts.append(f"{p.name}{ann}{default}")
    ret = "" if sig.return_annotation is inspect.Signature.empty else f" -> {sig.return_annotation}"
    doc = _doc(inspect.getdoc(fn), "    ")
    return f"def {name}({', '.join(parts)}){ret}:\n{doc}    ...\n"


def _api_block() -> str:
    out = []
    for n in (*API, "symbol_names"):
        out.append(_func(n, getattr(mtx.MetaTrader, n)))
    return "\n\n".join(out)


def _star_all(names: list[str]) -> str:
    return "__all__ = [\n" + "".join(f'    "{n}",\n' for n in names) + "]\n"


def init_stub() -> str:
    head = f'''{_doc(mtx.__doc__, "")}{BANNER}
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np

from ._version import __version__ as __version__
from .backends.base import API as API
from .client import MetaTrader as MetaTrader
from .constants import *
from .errors import (
{"".join(f"    {n} as {n},{chr(10)}" for n in ERRORS)})
from .types import (
{"".join(f"    {n} as {n},{chr(10)}" for n in TYPES)})
from .util import to_frame as to_frame
from .wineenv import setup_problems as setup_problems

MetaTraderX = MetaTrader

'''
    mod = "\n\n".join(_func(n, getattr(mtx, n)) for n in ("default", "set_default", "configure"))
    return head + mod + "\n\n" + _api_block() + "\n\n" + _star_all(sorted(mtx.__all__))


def offline_stub() -> str:
    import metatraderx.offline as off

    head = f'''{_doc(off.__doc__, "")}{BANNER}
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np

from .backends.base import API as API
from .client import MetaTrader as MetaTrader
from .constants import *
from .errors import *
from .types import *
from .util import to_frame as to_frame

'''
    mod = "\n\n".join(_func(n, getattr(off, n)) for n in ("default", "configure"))
    return head + mod + "\n\n" + _api_block() + "\n\n" + _star_all(sorted(off.__all__))


def build() -> dict[Path, str]:
    return {PKG / "__init__.pyi": init_stub(), PKG / "offline.pyi": offline_stub()}


def main() -> None:
    for path, text in build().items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
